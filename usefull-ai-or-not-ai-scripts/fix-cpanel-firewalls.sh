#!/bin/bash
#apply to multiple distros
# used gemini to fix across distros
#intended to fix cpanel firewalls from cmdline. who love using whm/cpanel web interface when you have terminal ?
#@todos: input allow ip list from cmdline
#deploy it with ansible on a list of servers ( see on additional scripts )

# ==========================================
# UNIVERSAL FIREWALL HARDENING SCRIPT
# Supports: iptables (CentOS 6), firewalld (CentOS 7+), ufw (Ubuntu/Debian)
# ==========================================

# Define your trusted administrative IPs / subnets here:
ADMIN_IPS=("8.5.2.8/28" "8.5.4.8/28")

# Ensure script is run as root
if [ "$EUID" -ne 0 ]; then
  echo "[-] Error: This script must be run as root."
  exit 1
fi

TIMESTAMP=$(date +%F_%T)

# Auto-detect firewall backend
if command -v firewall-cmd &> /dev/null && systemctl is-active --quiet firewalld; then
    ACTIVE_FW="firewalld"
elif command -v ufw &> /dev/null; then
    ACTIVE_FW="ufw"
elif command -v iptables &> /dev/null; then
    ACTIVE_FW="iptables"
else
    echo "[-] Error: No supported firewall backend (iptables, firewalld, ufw) found."
    exit 1
fi

echo "[+] Detected active firewall backend: $ACTIVE_FW"
echo "--------------------------------------------------"

case "$ACTIVE_FW" in
    "iptables")
        # 1. Save old settings
        echo "[1/7] Backing up old iptables configuration..."
        cp /etc/sysconfig/iptables "/etc/sysconfig/iptables.bak-$TIMESTAMP"

        # 2 & 3 & 4 & 5. Cleanup, Permit Admin IPs (SSH+cPanel), Public Services, and Drop rest
        echo "[2-5/7] Generating clean iptables ruleset..."
        
        # Build dynamic admin IP accept lines for iptables
        ADMIN_RULES=""
        for ip in "${ADMIN_IPS[@]}"; do
            ADMIN_RULES+="-A INPUT -s $ip -j ACCEPT\n"
        done

        cat << EOF > /etc/sysconfig/iptables
# Generated by Universal Hardening Script on $TIMESTAMP
*nat
:PREROUTING ACCEPT [0:0]
:POSTROUTING ACCEPT [0:0]
:OUTPUT ACCEPT [0:0]
COMMIT

*filter
:INPUT DROP [0:0]
:FORWARD DROP [0:0]
:OUTPUT ACCEPT [0:0]

# System & State Exemptions
-A INPUT -i lo -j ACCEPT
-A INPUT -m state --state RELATED,ESTABLISHED -j ACCEPT
-A INPUT -p icmp -j ACCEPT

# Trusted Admin Subnets (Full Access: SSH + cPanel + Everything)
$(echo -e "$ADMIN_RULES")

# Explicit Public Services (Web, Mail, DNS)
-A INPUT -p tcp -m state --state NEW -m multiport --dports 80,443 -j ACCEPT
-A INPUT -p tcp -m state --state NEW -m multiport --dports 25,465,587,110,995,143,993 -j ACCEPT
-A INPUT -p tcp -m state --state NEW --dport 53 -j ACCEPT
-A INPUT -p udp -m state --state NEW --dport 53 -j ACCEPT

# Known Threat Blocks
-A INPUT -s 46.148.40.0/24 -j DROP

# Default Catch-All Policy Drop
-A INPUT -j REJECT --reject-with icmp-host-prohibited
-A FORWARD -j REJECT --reject-with icmp-host-prohibited
COMMIT
EOF

        # 6. Save new configuration as golden backup
        echo "[6/7] Saving new golden baseline backup..."
        cp /etc/sysconfig/iptables /etc/sysconfig/iptables.gold-standard

        # 7. Apply changes
        echo "[7/7] Applying iptables changes..."
        service iptables restart
        ;;

    "firewalld")
        # 1. Save old settings
        echo "[1/7] Backing up old firewalld configuration..."
        cp -r /etc/firewalld "/etc/firewalld.bak-$TIMESTAMP"

        # 2. Cleanup current restrictions (Reset)
        echo "[2/7] Cleaning up/resetting firewalld rules..."
        firewall-cmd --complete-reload

        # 3 & 4. Permit admin IPs for SSH & cPanel (via Trusted Zone)
        echo "[3-4/7] Assigning admin IPs to trusted zone..."
        for ip in "${ADMIN_IPS[@]}"; do
            firewall-cmd --permanent --zone=trusted --add-source="$ip"
        done

        # 5. Permit public services on public zone and drop anything else
        echo "[5/7] Configuring public zone policies and public services..."
        firewall-cmd --permanent --zone=public --set-target=DROP
        firewall-cmd --permanent --zone=public --add-service=http
        firewall-cmd --permanent --zone=public --add-service=https
        firewall-cmd --permanent --zone=public --add-service=smtp
        firewall-cmd --permanent --zone=public --add-service=smtps
        firewall-cmd --permanent --zone=public --add-service=imap
        firewall-cmd --permanent --zone=public --add-service=imaps
        firewall-cmd --permanent --zone=public --add-service=pop3
        firewall-cmd --permanent --zone=public --add-service=pop3s
        firewall-cmd --permanent --zone=public --add-service=dns

        # 6. Save new configuration as golden backup
        echo "[6/7] Saving new golden baseline backup..."
        cp -r /etc/firewalld /etc/firewalld.gold-standard

        # 7. Apply changes
        echo "[7/7] Reloading firewalld..."
        firewall-cmd --reload
        ;;

    "ufw")
        # 1. Save old settings
        echo "[1/7] Backing up old ufw configuration..."
        cp /etc/ufw/before.rules "/etc/ufw/before.rules.bak-$TIMESTAMP"

        # 2. Cleanup current restrictions
        echo "[2/7] Resetting UFW..."
        ufw --force reset

        # Set default policy to drop incoming
        ufw default deny incoming
        ufw default allow outgoing

        # 3 & 4. Permit SSH & cPanel from admin IPs
        echo "[3-4/7] Whitelisting admin IPs for SSH and cPanel..."
        for ip in "${ADMIN_IPS[@]}"; do
            ufw allow from "$ip" to any port 22 proto tcp
            ufw allow from "$ip" to any port 2082 proto tcp
            ufw allow from "$ip" to any port 2083 proto tcp
            ufw allow from "$ip" to any port 2086 proto tcp
            ufw allow from "$ip" to any port 2087 proto tcp
        done

        # 5. Permit public services on public interface
        echo "[5/7] Permitting public services..."
        ufw allow 80/tcp
        ufw allow 443/tcp
        ufw allow 25/tcp
        ufw allow 465/tcp
        ufw allow 587/tcp
        ufw allow 110/tcp
        ufw allow 995/tcp
        ufw allow 143/tcp
        ufw allow 993/tcp
        ufw allow 53/tcp
        ufw allow 53/udp

        # 6. Save new configuration as golden backup
        echo "[6/7] Saving new golden baseline backup..."
        cp /etc/ufw/user.rules /etc/ufw/user.rules.gold-standard

        # 7. Apply changes
        echo "[7/7] Enabling and reloading UFW..."
        ufw --force enable
        ufw reload
        ;;
esac

echo "--------------------------------------------------"
echo "[✔] Firewall hardening completed successfully!"
